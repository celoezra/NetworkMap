def test_import_invalid_db(auth_headers):
    # Empty non-sqlite file
    with tempfile.NamedTemporaryFile(suffix=".db") as tmp:
        tmp.write(b"not a sqlite db")
        tmp.flush()
        files = {'file': ('invalid.db', open(tmp.name, 'rb'), 'application/octet-stream')}
        res = client.post("/api/admin/import", headers=auth_headers, files=files)
        assert res.status_code == 400
        assert "Chave do SQLCipher inválida ou arquivo corrompido" in res.json()["detail"]

def test_import_wrong_schema(auth_headers):
    with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as tmp:
        pass
    try:
        create_mock_db(tmp.name, valid=False)
        files = {'file': ('wrong_schema.db', open(tmp.name, 'rb'), 'application/octet-stream')}
        res = client.post("/api/admin/import", headers=auth_headers, files=files)
        assert res.status_code == 400
        # If it fails to parse valid sqlite structure/decrypts bad it might throw the generic cipher error, or specific table error.
        assert "Chave do SQLCipher inválida ou arquivo corrompido" in res.json()["detail"] or "não possui as tabelas" in res.json()["detail"]
    finally:
        os.remove(tmp.name)

def test_import_success_and_duplicate(auth_headers, db_session):
    with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as tmp:
        pass
    try:
        db_id = create_mock_db(tmp.name, valid=True)
        files = {'file': ('valid_import.db', open(tmp.name, 'rb'), 'application/octet-stream')}
        
        # First import should succeed
        res = client.post("/api/admin/import", headers=auth_headers, files=files)
        assert res.status_code == 200
        data = res.json()
        assert "sucesso" in data["message"]
        unit_id = data["new_unit_id"]
        
        # Verify unit created
        unit = db_session.query(Unit).filter_by(id=unit_id).first()
        assert unit is not None
        assert db_id in unit.description
        
        # Second import should fail due to duplicate detection
        files = {'file': ('valid_import_dup.db', open(tmp.name, 'rb'), 'application/octet-stream')}
        res2 = client.post("/api/admin/import", headers=auth_headers, files=files)
        assert res2.status_code == 409
        assert "já foi importado" in res2.json()["detail"]

    finally:
        os.remove(tmp.name)
