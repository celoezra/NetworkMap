def create_mock_db(filepath, valid=True, db_id=None):
    if db_id is None:
        db_id = str(uuid.uuid4())
    conn = sqlite3.connect(filepath)
    cursor = conn.cursor()
    
    # Needs the proper SQLCipher key context
    # Usually we bypass this if the test uses the same key_manager.
    # To properly mock a DB generated by NetworkMap, we must fetch the current dev key.
    from app.security.key_manager import get_or_create_database_key
    db_key = get_or_create_database_key()
    safe_key = db_key.replace("'", "''")
    cursor.execute(f"PRAGMA key = '{safe_key}'")
    
    if valid:
        cursor.execute('CREATE TABLE database_metadata (id INTEGER PRIMARY KEY, application_name TEXT, database_id TEXT, schema_version INTEGER, organization_id TEXT, created_by_version TEXT, created_at TEXT)')
        cursor.execute(f'INSERT INTO database_metadata (application_name, database_id, schema_version) VALUES (\'NetworkMap\', \'{db_id}\', 1)')
        cursor.execute('CREATE TABLE racks (id INTEGER PRIMARY KEY, uuid TEXT, unit_id INTEGER, name TEXT, location_description TEXT, description TEXT, notes TEXT, created_at TEXT, updated_at TEXT)')
        cursor.execute(f'INSERT INTO racks (uuid, name, location_description) VALUES (\'{str(uuid.uuid4())}\', \'Mock Rack\', \'Test Location\')')
        cursor.execute('CREATE TABLE switches (id INTEGER PRIMARY KEY, uuid TEXT, unit_id INTEGER, name TEXT, hostname TEXT, manufacturer TEXT, model TEXT, ip_address TEXT, mac_address TEXT, port_count INTEGER, rack_id INTEGER, rack_position TEXT, notes TEXT, created_at TEXT, updated_at TEXT)')
        cursor.execute('CREATE TABLE devices (id INTEGER PRIMARY KEY, uuid TEXT, unit_id INTEGER, name TEXT, hostname TEXT, ip_address TEXT, mac_address TEXT, device_type TEXT, location_id INTEGER, vlan_id INTEGER, manufacturer TEXT, model TEXT, asset_tag TEXT, serial_number TEXT, description TEXT, notes TEXT, created_at TEXT, updated_at TEXT)')
        cursor.execute('CREATE TABLE locations (id INTEGER PRIMARY KEY, uuid TEXT, unit_id INTEGER, name TEXT, sector TEXT, floor TEXT, description TEXT, notes TEXT, created_at TEXT, updated_at TEXT)')
        cursor.execute('CREATE TABLE vlans (id INTEGER PRIMARY KEY, uuid TEXT, unit_id INTEGER, vlan_number INTEGER, name TEXT, description TEXT, subnet TEXT, gateway TEXT, created_at TEXT, updated_at TEXT)')
        cursor.execute('CREATE TABLE switch_ports (id INTEGER PRIMARY KEY, uuid TEXT, unit_id INTEGER, switch_id INTEGER, port_number INTEGER, name TEXT, description TEXT, vlan_id INTEGER, destination_location_id INTEGER, connected_device_id INTEGER, connection_type TEXT, status TEXT, notes TEXT, created_at TEXT, updated_at TEXT)')
        cursor.execute('CREATE TABLE connections (id INTEGER PRIMARY KEY, uuid TEXT, unit_id INTEGER, source_port_id INTEGER, target_port_id INTEGER, description TEXT, created_at TEXT)')
    else:
        # Invalid schema
        cursor.execute("CREATE TABLE dummy (id INTEGER)")

    conn.commit()
    conn.close()
    return db_id

